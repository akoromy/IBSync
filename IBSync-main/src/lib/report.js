import { jsPDF } from 'jspdf'
import { format } from 'date-fns'

// Clinician-facing 1–2 page summary. Plain, scannable, numbers first.
export function exportReport({ state, ctx, questions }) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const W = doc.internal.pageSize.getWidth()
  const M = 48
  let y = 56
  const ink = [42, 38, 33], muted = [107, 99, 88], moss = [78, 130, 115], brick = [169, 87, 60]

  const line = (txt, size = 10.5, color = ink, bold = false, gap = 4) => {
    doc.setFont('helvetica', bold ? 'bold' : 'normal')
    doc.setFontSize(size)
    doc.setTextColor(...color)
    const lines = doc.splitTextToSize(String(txt), W - M * 2)
    for (const l of lines) {
      if (y > 790) { doc.addPage(); y = 56 }
      doc.text(l, M, y)
      y += size + gap
    }
  }
  const head = txt => { y += 10; doc.setDrawColor(229, 223, 210); doc.line(M, y - 6, W - M, y - 6); y += 8; line(txt, 12.5, moss, true, 6) }

  line('IBSync — patient summary for clinician', 17, ink, true, 6)
  line(`Prepared ${format(new Date(), 'd MMM yyyy')} · Period: last 28 days · Self-reported data`, 9.5, muted)
  line(`Age ${state.profile.age} · Diagnosed ${state.profile.diagnosed} · Recorded subtype: ${state.profile.subtype}`, 10, muted)

  if (ctx.redFlags.length) {
    head('Alarm features reported')
    ctx.redFlags.forEach(r => line(`• ${r.label}`, 10.5, brick, true))
  }

  head('Symptoms')
  const s = ctx.series
  const logged = s.filter(d => d.logged)
  const flares = s.filter(d => d.maxPain >= 6).length
  const avg = (logged.reduce((a, d) => a + (d.maxPain || 0), 0) / Math.max(1, logged.length)).toFixed(1)
  line(`Flare days (worst pain 6+/10): ${flares} of ${logged.length} logged days. Mean daily worst pain: ${avg}/10.`)
  line(`Last 7 days: ${ctx.week.flaresNow} flare days (previous 7: ${ctx.week.flaresPrev}).`)

  head('Bowel pattern (Bristol)')
  const st = ctx.stool
  line(`${st.total} stools logged, ~${st.perDay}/day. Type 1–2: ${st.hardPct}% · Type 3–5: ${st.normalPct}% · Type 6–7: ${st.loosePct}%. Urgent: ${st.urgent}. Blood reported: ${st.blood}.`)
  line(`Distribution: ${st.dist.map(d => `T${d.type}=${d.count}`).join('  ')}. Pattern by Rome IV stool criteria: ${st.subtype} (self-report; for clinician confirmation).`)

  head('Possible dietary triggers (association in self-logs)')
  ctx.triggers.slice(0, 5).forEach(f => line(`• ${f.food.name}: symptoms within 6h after ${f.reactions}/${f.n} meals (${f.rate}%). FODMAP: ${f.food.fodmap}.`))
  line(`Components: ${ctx.tags.slice(0, 4).map(t => `${t.label} ${t.rate}%`).join(', ')}. Baseline post-meal symptom rate across all meals for comparison.`, 9.5, muted)

  head('Lifestyle associations')
  ctx.lifestyle.forEach(l => line(`• ${l.factor}: flare-day rate ${l.flareHigh ?? '–'}% on ${l.highLabel} vs ${l.flareLow ?? '–'}% on ${l.lowLabel} (r=${l.r}).`))

  head('Medication & adherence (14 days)')
  ctx.adherence.forEach(a => line(`• ${a.med.label} (${a.med.times.join(', ')}): ${a.pct}% taken. ${a.reasons.length ? 'Missed mainly: ' + a.reasons.slice(0, 2).map(r => `${r[0]} ×${r[1]}`).join('; ') : ''}`))
  const prn = state.profile.meds.filter(m => m.prn)
  if (prn.length) line(`As-needed: ${prn.map(m => m.label).join(', ')}.`, 10, muted)

  head('Patient\'s questions for this visit')
  ;(questions || []).forEach((q, i) => line(`${i + 1}. ${q}`))
  state.concerns.forEach(c => line(`• Patient noted: ${c}`))

  y += 8
  line('Generated by IBSync from patient self-tracking. Associations are not causation. Not a diagnostic document.', 8.5, muted)
  doc.save(`IBSync-summary-${format(new Date(), 'yyyy-MM-dd')}.pdf`)
}
